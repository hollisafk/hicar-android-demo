/*
 * psk_speke.h - optional PSK-SPEKE passwordless re-authentication layer.
 *
 * Reverse engineered from HwDeviceAuth (cdex / libHwDeviceAuthSDK.so).
 * Huawei's "PSK-SPEKE" is NOT a separate handshake: the peers derive a
 * temporary authentication key from a cached long-term PSK and feed its
 * hex string into the ordinary SPEKE PAKE as the PIN. All of the PAKE /
 * HKDF / big-number code is therefore reused unchanged.
 *
 * This module supplies only the missing pieces:
 *   1. persist a per-peer PSK after a successful first BIND;
 *   2. derive tmpAuthKey = HKDF(PSK, salt=nonce, info="hichain_tmp_auth_enc_key");
 *   3. render tmpAuthKey as a 64-character hex PIN and inject it through the
 *      existing get_protocol_params callback.
 *
 * It is compiled only when _ENABLE_PSK_SPEKE_ is defined, and is inert until
 * psk_speke_set_enabled(1) is called at runtime. With the switch off, the
 * receiver behaves byte-for-byte as before.
 *
 * Scope note: the PSK here is the session key agreed during the first BIND
 * (both peers provably hold the same value). Huawei derives its PSK from an
 * X25519 long-term key pair inside HwAssetManager/TEE. psk_speke_set_psk()
 * is the seam where a long-term-ECDH PSK can be plugged in later without
 * touching the rest of the layer.
 */
#ifndef PSK_SPEKE_H
#define PSK_SPEKE_H

#include <stdint.h>
#include "hichain.h" /* struct hc_pin / hc_auth_id / hc_session_key */

#define PSK_SPEKE_MAGIC          "HCARPSK1"
#define PSK_SPEKE_MAGIC_LEN      8
#define PSK_SPEKE_PSK_LEN        32
#define PSK_SPEKE_NONCE_LEN      32
#define PSK_SPEKE_TMP_KEY_LEN    32
#define PSK_SPEKE_PIN_HEX_LEN    (PSK_SPEKE_TMP_KEY_LEN * 2) /* 64 */
#define PSK_SPEKE_MAX_SLOTS      8
#define PSK_SPEKE_SLOT_LEN       68  /* id_hash[32] + psk[32] + used[1] + rsv[3] */
#define PSK_SPEKE_FILE           "psk_speke.bin"
#define PSK_SPEKE_FILE_LEN       (PSK_SPEKE_MAGIC_LEN + 4 + PSK_SPEKE_MAX_SLOTS * PSK_SPEKE_SLOT_LEN)

#define PSK_SPEKE_HKDF_INFO      "hichain_tmp_auth_enc_key"
#define PSK_SPEKE_STORE_INFO     "hichain_psk_speke_store_key"
#define PSK_SPEKE_STORE_SALT     "hichain_psk_speke_salt_v1"
#define PSK_SPEKE_NONCE_INFO     "hichain_psk_speke_nonce_v1"

#define PSK_SPEKE_OK             0
#define PSK_SPEKE_ERR           (-1)

/* Process-wide runtime switch. Default OFF. */
int  psk_speke_is_enabled(void);
void psk_speke_set_enabled(int on);

/* File backend, injected by android_jni.c (reuses hks file callbacks). */
typedef int32_t (*psk_speke_read_fn)(const char *name, uint32_t off,
                                     uint8_t *buf, uint32_t len);
typedef int32_t (*psk_speke_write_fn)(const char *name, uint32_t off,
                                      const uint8_t *buf, uint32_t len);
void psk_speke_init(psk_speke_read_fn reader, psk_speke_write_fn writer);

/* RFC 5869 HKDF-SHA256. Exposed for the host-side self test. */
int psk_speke_hkdf(const uint8_t *ikm, uint32_t ikm_len,
                   const uint8_t *salt, uint32_t salt_len,
                   const char *info, uint32_t out_len, uint8_t *out);

/*
 * Shared 32-byte nonce. IMPORTANT: both peers must derive the same value.
 * The peer auth id is NOT usable here (A's peer is B while B's peer is A),
 * so the nonce is bound to the PSK itself, which is identical on both sides.
 * A real Huawei phone carries a fresh 32-byte nonce in payload.nonce;
 * psk_speke_set_nonce() lets the message layer feed that value in when that
 * path is wired up. Freshness of each SPEKE run still comes from the random
 * salt/epk generated by pake_server.c, so a stable PIN is safe here.
 */
int  psk_speke_derive_nonce(const uint8_t psk[PSK_SPEKE_PSK_LEN],
                            uint8_t out[PSK_SPEKE_NONCE_LEN]);
void psk_speke_set_nonce(const uint8_t nonce[PSK_SPEKE_NONCE_LEN]);
void psk_speke_clear_nonce(void);

/* tmpAuthKey -> hex PIN. Requires HC_PIN_BUFF_LEN >= 64 (see hichain.h). */
int psk_speke_build_pin(const uint8_t psk[PSK_SPEKE_PSK_LEN],
                        const uint8_t nonce[PSK_SPEKE_NONCE_LEN],
                        struct hc_pin *out);

/* Per-peer PSK store, keyed by SHA256(peer auth id). */
int psk_speke_save(const struct hc_auth_id *peer, const struct hc_session_key *session_key);
int psk_speke_load(const struct hc_auth_id *peer, uint8_t psk[PSK_SPEKE_PSK_LEN]);
int psk_speke_has(const struct hc_auth_id *peer);
int psk_speke_forget(const struct hc_auth_id *peer);

/* Seam for plugging a Huawei-style X25519 long-term PSK in later. */
int psk_speke_set_psk(const struct hc_auth_id *peer,
                      const uint8_t psk[PSK_SPEKE_PSK_LEN]);

#endif /* PSK_SPEKE_H */
